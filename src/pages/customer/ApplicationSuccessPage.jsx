import { useState } from 'react';
import { useLocation } from 'react-router-dom';
import {
  AlertCircle,
  ArrowLeft,
  Check,
  CheckCircle2,
  Copy,
  FilePlus2,
} from 'lucide-react';
import Button from '../../components/common/Button';

export default function ApplicationSuccessPage() {
  const location = useLocation();
  const [copied, setCopied] = useState(false);

  const submissionConfirmed = Boolean(location.state?.submissionConfirmed);
  const referenceId = location.state?.referenceId;

  async function handleCopyReferenceId() {
    if (!referenceId || !navigator.clipboard) return;
    try {
      await navigator.clipboard.writeText(String(referenceId));
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Clipboard permissions may restrict copy; reference ID remains clearly selectable.
    }
  }

  // Guard against direct navigation without an actual confirmed backend submission.
  if (!submissionConfirmed || !referenceId) {
    return (
      <div className="bg-lf-bg py-16 sm:py-24">
        <div className="mx-auto max-w-lg px-4 sm:px-6">
          <div className="rounded-[18px] border border-lf-line bg-white p-8 text-center shadow-[0_18px_55px_rgba(16,37,65,0.09)]">
            <div className="mx-auto flex h-14 w-14 items-center justify-center rounded-full bg-amber-50 text-amber-600">
              <AlertCircle className="h-7 w-7" aria-hidden="true" />
            </div>
            <h1 className="mt-5 text-2xl font-bold tracking-tight text-lf-navy">
              No Confirmed Submission Found
            </h1>
            <p className="mt-3 text-sm leading-relaxed text-lf-muted">
              An enquiry reference ID is generated by our server only after you
              complete and submit the personal loan enquiry form.
            </p>
            <div className="mt-7 flex flex-col gap-3 sm:flex-row sm:justify-center">
              <Button to="/apply">
                <FilePlus2 className="h-4 w-4" aria-hidden="true" />
                Start Loan Enquiry
              </Button>
              <Button to="/" variant="outline">
                <ArrowLeft className="h-4 w-4" aria-hidden="true" />
                Return to Home
              </Button>
            </div>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="bg-lf-bg py-14 sm:py-20">
      <div className="mx-auto max-w-xl px-4 sm:px-6">
        <div className="rounded-[18px] border border-lf-line bg-white p-7 text-center shadow-[0_18px_55px_rgba(16,37,65,0.09)] sm:p-10">
          <div className="mx-auto flex h-16 w-16 items-center justify-center rounded-full bg-lf-green-soft text-lf-green">
            <CheckCircle2 className="h-9 w-9" aria-hidden="true" />
          </div>

          <h1 className="mt-6 text-2xl font-bold tracking-tight text-lf-navy sm:text-3xl">
            Your enquiry has been submitted successfully.
          </h1>

          <p className="mt-3 text-sm leading-relaxed text-lf-muted sm:text-base">
            Thank you for sharing your personal loan requirement with LoanFlow.
            Please keep your official reference ID below for your records.
          </p>

          {/* Official Backend Reference ID (Prototype .ref style) */}
          <div className="mx-auto mt-6 max-w-sm rounded-[10px] border border-dashed border-[#8bcbb5] bg-[#f2f7f5] px-5 py-4">
            <p className="text-[11px] font-bold uppercase tracking-[0.5px] text-lf-muted">
              Reference ID
            </p>
            <div className="mt-2 flex flex-wrap items-center justify-center gap-3">
              <span className="tabular-nums select-all text-xl font-extrabold tracking-wide text-lf-navy sm:text-2xl">
                {referenceId}
              </span>
              <button
                type="button"
                onClick={handleCopyReferenceId}
                className="inline-flex items-center gap-1.5 rounded-lg border border-lf-line bg-white px-2.5 py-1 text-xs font-bold text-lf-navy hover:bg-lf-bg cursor-pointer"
                aria-label="Copy reference ID"
              >
                {copied ? (
                  <>
                    <Check className="h-3.5 w-3.5 text-lf-green" aria-hidden="true" />
                    Copied
                  </>
                ) : (
                  <>
                    <Copy className="h-3.5 w-3.5" aria-hidden="true" />
                    Copy
                  </>
                )}
              </button>
            </div>
          </div>

          {/* Transparent Follow-Up Expectation */}
          <div className="mt-6 rounded-[11px] border border-lf-green-border bg-lf-green-tint px-4 py-3.5 text-left text-xs leading-relaxed text-[#40536a] sm:text-sm">
            <p>
              <strong className="font-bold text-lf-navy">
                What happens next:{' '}
              </strong>
              Our team or the relevant lending/distribution partner may contact
              you on your submitted mobile number regarding your enquiry.
              Submission does not guarantee loan approval; eligibility, terms,
              and final approval are evaluated independently by the lending
              partner.
            </p>
          </div>

          <div className="mt-8 flex justify-center">
            <Button to="/" size="lg">
              <ArrowLeft className="h-4 w-4" aria-hidden="true" />
              Return to Home
            </Button>
          </div>
        </div>
      </div>
    </div>
  );
}
